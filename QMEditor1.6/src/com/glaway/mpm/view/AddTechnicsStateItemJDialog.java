	private void loadDatas() {
		int row = this.parentPanel.table.getSelectedRow();
		makeDeptComboBox.setSelectedItem((String) this.parentPanel.table.getValueAt(row, 1));
		useDeptComboBox.setSelectedItem((String) this.parentPanel.table.getValueAt(row, 2));
		String text = (String) this.parentPanel.table.getValueAt(row, 3);
		if(text != null) {
			text = CommonHelper.replaceReadSeperator(text, WorkSpaceUtil.getTechnicsPath(currentTech));
		}
		speCharPanel.setText(text);
		insertImgTextField.setText((String) this.parentPanel.table.getValueAt(row, 4));
		oldPath = (String) this.parentPanel.table.getValueAt(row, 4);

		String techNumber = currentTech.attributeValue("technicsNumber");

		String techDir = WorkSpaceUtil.getTechnicsDirectory(techNumber);
		String imageP = String.valueOf(this.parentPanel.table.getValueAt(row, 5));

		String filePath = techDir + File.separator + imageP;
		showImage(filePath);
	}

	private void chooseButtonActionPerformed(ActionEvent evt) {
		// 选择图片
		String filepath = FileChooserTool.getFilePath("jpg", this.dialog);
		System.out.println("-------filepath---"+filepath);
		//File file = getAttachFile();
		if(filepath == null || "".equals(filepath)) {
			insertImgTextField.setText("");
			showImage(null);
		} else {
			insertImgTextField.setText(filepath);
			showImage(filepath);
		}

	}

	private void showImage(String filepath) {
		int width = previewPanel.getWidth()-10;
		int height = previewPanel.getHeight()-25;
		if(filepath == null || "".equals(filepath)) {
			jLabel5.setIcon(null);

	        p.removeAll();
	        p.add(jLabel5);
	        p.setVisible(true);
//	        p.setBounds(5, 15, width, height);

	        previewPanel.removeAll();
	        previewPanel.add(p);
	        dialog.pack();
		} else {
			ImageIcon imageIcon = new ImageIcon(filepath);
	        imageIcon.setImage(imageIcon.getImage().getScaledInstance(width, height, Image.SCALE_DEFAULT));
	        jLabel5.setIcon(imageIcon);

	        p.removeAll();
	        p.add(jLabel5);
	        p.setVisible(true);
//	        p.setBounds(5, 15, width, height);

	        previewPanel.removeAll();
	        previewPanel.add(p);
	        dialog.pack();
		}

	}

	private void sureButtonActionPerformed(ActionEvent evt) {
		//点击确定按钮
		TechnicsStateTableBean bean = new TechnicsStateTableBean();
		bean.setZzdw(makeDeptComboBox.getSelectedItem().toString());
		bean.setSydw(useDeptComboBox.getSelectedItem().toString());
		bean.setGyzt(speCharPanel.getText());
		if(insertImgTextField.getText() == null || "".equals(insertImgTextField.getText())) {
			if(oldPath == null || "".equals(oldPath)) {
				bean.setImagePath("");
			} else {
				bean.setImagePath("");
				bean.setChangeFile(true);
			}
		} else if (oldPath == null || !oldPath.equals(insertImgTextField.getText())) {
			bean.setImagePath(insertImgTextField.getText());
			bean.setChangeFile(true);
		}
		if(this.flag == 0) {
			parentPanel.addToTable(bean);
		} else {
			parentPanel.update(bean, this.parentPanel.table.getSelectedRow());
		}

		dialog.setVisible(false);
	}

	private void cancelButtonActionPerformed(ActionEvent evt) {
		//点击取消按钮
		dialog.setVisible(false);
	}

	/**
	 * 将dialog屏幕居中显示
	 *
	 */
	public static void setMiddleOnScreenWithDialog(JDialog dialog){
		int windowWidth = dialog.getWidth();                     //获得窗口宽
	    int windowHeight = dialog.getHeight();                   //获得窗口高
	    Toolkit kit = Toolkit.getDefaultToolkit();              //定义工具包
	    Dimension screenSize = kit.getScreenSize();             //获取屏幕的尺寸
	    int screenWidth = screenSize.width;                     //获取屏幕的宽
	    int screenHeight = screenSize.height;                   //获取屏幕的高
	    dialog.setLocation(screenWidth/2-windowWidth/2, screenHeight/2-windowHeight/2);//设置窗口居中显示
	}

