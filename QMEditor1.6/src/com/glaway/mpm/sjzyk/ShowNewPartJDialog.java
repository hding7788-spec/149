    private void remove(ActionEvent evt) {
        int rows = jTable1.getRowCount();
        if (rows == 0) {
            JOptionPane.showMessageDialog(this, "没有需要移除的数据！");
        } else {
            int[] sels = jTable1.getSelectedRows();
            if (sels == null || sels.length == 0) {
                JOptionPane.showMessageDialog(this, "请选择需要移除的数据！");
            } else {
                DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
                Element techEle = null;
                XWTreeNode currentTechNode = frame.technicsTreePanel.getSelectedTreeNode();
                XWTreeObject treeObj = currentTechNode.getObject();
                if (treeObj instanceof XWTechnicsTreeObject) {
                    XWTechnicsTreeObject techObj = (XWTechnicsTreeObject) treeObj;
                    techEle = techObj.getTreeCellData();
                }

                if (techEle == null) {
                    JOptionPane.showMessageDialog(frame, "没有找到工艺数据，请选择工艺文件进行工艺定额！");
                    return;
                }
                Map<String, PDFBuilder.CzjPart> czjPartMap = PDFBuilder.getAllCzjMap(techEle);
                String message = "";
                for (int i : sels) {
                    String partNumber = (String) tableModel.getValueAt(i, 2);
                    if (czjPartMap.containsKey(partNumber)) {
                        if("".equals(message)){
                            message  = partNumber;
                        }else{
                            message = message + "," + partNumber;
                        }
                    }
                }
                if("".equals(message)){
                    for (int i = 0; i < sels.length; i++) {
                        tableModel.removeRow(jTable1.getSelectedRow());
                    }
                }else{
                    JOptionPane.showMessageDialog(frame, message + "已参与参装，请先取消参装再进行删除！");
                    return;
                }
            }
        }
    }

    private void save(ActionEvent evt) {

        if (!CommonUtil.checkValueIsNull(jTable1.getModel(), new int[]{4, 5})) {
            JOptionPane.showMessageDialog(this, "工艺数量、单位不能为空！");
            return;
        }
        if (!CommonUtil.checkIsNumeric(jTable1.getModel(), new int[]{4})) {
            JOptionPane.showMessageDialog(this, "工艺数量只能填写0-9的数字！！");
            return;
        }

        int flag = JOptionPane.showConfirmDialog(this, "确定保存吗？", "确认", JOptionPane.OK_CANCEL_OPTION);
        if (flag == JOptionPane.YES_OPTION) {
            //当前工艺
            Element techEle = null;
            XWTreeNode currentTechNode = frame.technicsTreePanel.getSelectedTreeNode();
            XWTreeObject treeObj = currentTechNode.getObject();
            if (treeObj instanceof XWTechnicsTreeObject) {
                XWTechnicsTreeObject techObj = (XWTechnicsTreeObject) treeObj;
                techEle = techObj.getTreeCellData();
            }

            if (techEle == null) {
                JOptionPane.showMessageDialog(this, "没有找到工艺数据，请选择工艺文件进行工艺定额！");
                return;
            }

            //获取工艺定额元素下查询创建的标准间/元器件/外购件子元素
            Element gyde = XmlUtility.getTechnicsDEElement(techEle);
            Element newpart = XmlUtility.getChildElements(gyde, "SJZYKNEWPART");
            if (newpart == null) {
                newpart = DocumentHelper.createElement("SJZYKNEWPART");
            } else {
                Map<String, PDFBuilder.CzjPart> map = PDFBuilder.getAllCzjMap(techEle);
                Map<String, String> newPartMap = new HashMap<String, String>();
                List<Element> newParts = newpart.elements("SjzykNewPart");
                for (Element newPart : newParts) {
                    newPartMap.put(newPart.attributeValue("sjbm"), newPart.attributeValue("gysl"));
                }
                for (int i = 0; i < jTable1.getRowCount(); i++) {
                    String partNumber = (String) jTable1.getModel().getValueAt(i, 2);
                    String setCount = (String) jTable1.getModel().getValueAt(i, 4);
                    if (map.containsKey(partNumber)) {
                        double useCount = map.get(partNumber).getCount();
                        if (newPartMap.get(partNumber) != null && useCount > Double.valueOf(setCount)) {
                            JOptionPane.showMessageDialog(frame, "参装件:" + partNumber + "，已参装数量为：" + useCount + "，超出当前设置数量：" + setCount + "，保存失败！");
                            return;
                        }
                    }
                }
                XmlUtility.deleteAllChildElements(newpart);
            }

            DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
            SjzykBean bean = null;
            for (int i = 0; i < jTable1.getRowCount(); i++) {
                bean = (SjzykBean) tableModel.getValueAt(i, 8);
                bean.setGysl((String) jTable1.getValueAt(i, 4));
                bean.setDw((String) jTable1.getValueAt(i, 5));


                Element newPartEle = CommonUtil.createPartElement(i, bean, "SjzykNewPart");
                newpart.add(newPartEle);
            }

            //gyde.add(newpart);

            String techPath = WorkSpaceUtil.getTechnicsDirectory(techEle.attributeValue("technicsNumber"));
            String xmlFilePath = techPath + File.separator + techEle.attributeValue("technicsNumber") + ".xml";
            System.out.println("_-----------------------<><><>" + techPath);
            try {
                XmlUtility.saveDocument(techEle.getDocument(), xmlFilePath);
            } catch (Exception e1) {
                e1.printStackTrace();
            }

            UploadTechnics technics = ObjectTransfer.technicsElementToUploadTechnics(techEle);
            if (!frame.editTechnics.contains(technics)) {
                frame.editTechnics.add(technics);
            }
        }

        this.setVisible(false);
    }

    private void loadData() {
        Element techEle = null;
        XWTreeNode currentTechNode = frame.technicsTreePanel.getSelectedTreeNode();
        XWTreeObject treeObj = currentTechNode.getObject();
        if (treeObj instanceof XWTechnicsTreeObject) {
            XWTechnicsTreeObject techObj = (XWTechnicsTreeObject) treeObj;
            techEle = techObj.getTreeCellData();
        }

        List<SjzykBean> list = new ArrayList<SjzykBean>();
        //获取工艺定额元素下的标准间/元器件子元素
        Element gyde = XmlUtility.getTechnicsDEElement(techEle);
        List<Element> matchParts = XmlUtility.getTechnicsSJZYKGYDENewPart(gyde);
        if (matchParts != null && !matchParts.isEmpty()) {
            for (Element element : matchParts) {
                list.add(CommonUtil.creatSjzykBean(element));
            }
        }

        for (SjzykBean bean : list) {
            setRowValues(bean);
        }
    }

    private void setRowValues(SjzykBean bean) {
        //新增一行
        DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
        Vector<String> vector = new Vector<String>();
        for (int i = 0; i < tableModel.getColumnCount(); i++) {
            vector.add("");
        }
        tableModel.addRow(vector);

        //写入数据
        int n = jTable1.getRowCount() - 1;

        //"序号", "编码", "设计编码", "名称", "工艺数量", "单位", "规格", "类型", "object","备注"
        tableModel.setValueAt(jTable1.getRowCount(), n, 0);
        tableModel.setValueAt(bean.getPartNumber(), n, 1);
        tableModel.setValueAt(bean.getSjbm(), n, 2);
        tableModel.setValueAt(bean.getName(), n, 3);
        tableModel.setValueAt(bean.getGysl(), n, 4);
        tableModel.setValueAt(bean.getDw(), n, 5);
        if ("标准件".equals(bean.getDataType())) {

            tableModel.setValueAt(bean.getGg(), n, 6);
        } else {
            tableModel.setValueAt(bean.getXhgg(), n, 6);
        }
        tableModel.setValueAt(CommonUtil.formatType(bean.getDataType()), n, 7);
        tableModel.setValueAt(bean, n, 8);
        tableModel.setValueAt(bean.getComment(), n, 9);
    }

