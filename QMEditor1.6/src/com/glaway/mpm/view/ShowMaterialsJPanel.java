    public void setValues(Element partElement, boolean flag, boolean isSop) {
    	DefaultTableModel tableModel = (DefaultTableModel)jTable1.getModel();
    	tableModel.setRowCount(0);
    	String mtype = partElement.attributeValue("MTYPE");
    	List<Map<String,String>> list = frame.getAttriMap().get(mtype);
		if(isSop){
			list.clear();
			setTitle("SOP体系BOM信息");
			list = SopPbomUtil.getPartInfo(partElement);
			loadData(list, partElement, tableModel);
		}else{
			if ("标准件".equals(mtype)) {
				setTitle("标准件材料信息");
				//map = LoadMaterialsConfig.getInstance().getAttributes("BZJ_");
			} else if ("元器件".equals(mtype)) {
				setTitle("元器件材料信息");
				//map = LoadMaterialsConfig.getInstance().getAttributes("YQJ_");
			} else if ("自制件".equals(mtype)) {
				setTitle("自制件材料信息");
				//map = LoadMaterialsConfig.getInstance().getAttributes("DEFAULT_");
			}

			if (list != null && flag) {
				loadData(list, partElement, tableModel);
			} else {
				setTitle("设计属性信息");
				list = LoadDesignAttributes.getInstance().getAllDesignAttr();
				loadData(list, partElement, tableModel);
			}

		}

    }

    private void loadData(List<Map<String,String>> list, Element partElement, DefaultTableModel tableModel) {
    	String name = "";
    	String displayName = "";

    	if(list != null && !list.isEmpty()) {
    		int index = 0;
    		for (Map<String, String> map : list) {
    			name = String.valueOf(map.keySet().toArray()[0]);
    			if(name == null || "".equals(name) || "null".equals(name)){
    				continue;
				}
        		displayName = map.get(name);

        		if((index == 6) || (jTable1.getRowCount() == 0)) {
        			//新增一行
            		Vector<String> vector = new Vector<String>();
            		for (int i = 0; i < tableModel.getColumnCount(); i++) {
            			vector.add("");
            		}
            		tableModel.addRow(vector);
            		index = 0;
        		}

        		tableModel.setValueAt(displayName+":", jTable1.getRowCount()-1, index++);
        		tableModel.setValueAt(partElement.attributeValue(name), jTable1.getRowCount()-1, index++);
			}
    	}

    	setDuiqi();
    }

