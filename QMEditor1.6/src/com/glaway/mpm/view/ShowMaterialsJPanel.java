    //设置JTable表格单元格对齐的效果
  	public void setDuiqi() {
  		DefaultTableCellRenderer right = new DefaultTableCellRenderer();
  		right.setHorizontalAlignment(JLabel.RIGHT);
  		right.setBackground(getBackground());//new Color(236,233,216)

  		DefaultTableCellRenderer left = new DefaultTableCellRenderer();
  		left.setHorizontalAlignment(JLabel.LEFT);
  		left.setBackground(getBackground());//new Color(236,233,216)

		for(int i = 0; i< jTable1.getColumnCount();i++) {
			TableColumn col = jTable1.getColumn(jTable1.getColumnName(i));
			if(i%2==0){
				col.setCellRenderer(right);
			} else {
				col.setCellRenderer(left);
			}
			this.setSize(getWidth(), 50);
		}
  	}

