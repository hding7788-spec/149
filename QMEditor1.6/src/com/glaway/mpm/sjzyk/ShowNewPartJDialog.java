    public void setValues(List<Object> list, String dataType) {
        if (list == null || list.isEmpty()) {
            return;
        }

        //过滤在该表中已经存在的数据，删除在该表中有而在选择界面中被移除掉的数据
        list = processData(list, dataType);

        SjzykBean bean = null;
        for (Object obj : list) {
            if (obj instanceof SjzykBean) {
                bean = (SjzykBean) obj;
                setRowValues(bean);
            }
        }
    }

    private List<Object> processData(List<Object> list, String dataType) {
        List<String> allData = getAllDataByDataType(dataType);
        if (allData == null || allData.isEmpty()) {
            return list;
        }

        //保存需要删除的数据
        List<String> deleteList = new ArrayList<String>(allData);

        //保存需要新添加的数据
        List<Object> addList = new ArrayList<Object>(list);

        SjzykBean bean = null;
        for (Object object : list) {
            if (object instanceof SjzykBean) {
                bean = (SjzykBean) object;

                //过滤已经存在的数据
                if (allData.contains(bean.getNumber())) {
                    addList.remove(object);
                    deleteList.remove(bean.getNumber());
                }
            }
        }

        //从表中删除被移除的数据
        if (deleteList.isEmpty()) {
            return addList;
        }
        int rows = jTable1.getRowCount();
        if (rows < 0) {
            return addList;
        }

        List<Integer> delRows = new ArrayList<Integer>();
        DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
        for (int i = 0; i < rows; i++) {
            String number = (String) tableModel.getValueAt(i, 1);
            if (deleteList.contains(number)) {
                delRows.add(i);
            }
        }

        if (!delRows.isEmpty()) {
            for (Integer integer : delRows) {
                tableModel.removeRow(integer);
            }
        }

        return addList;
    }

    private List<String> getAllDataByDataType(String dataType) {
        int rows = jTable1.getRowCount();
        if (rows < 0) {
            return null;
        }
        List<String> list = new ArrayList<String>();
        DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
        SjzykBean bean = null;
        for (int i = 0; i < rows; i++) {
            bean = (SjzykBean) tableModel.getValueAt(i, 8);
            if (dataType.equals(bean.getDataType())) {
                list.add(bean.getNumber());
            }
        }
        return list;
    }

    public List<SjzykBean> getDataByDataType(String dataType) {
        int rows = jTable1.getRowCount();
        if (rows < 0) {
            return null;
        }
        List<SjzykBean> list = new ArrayList<SjzykBean>();
        DefaultTableModel tableModel = (DefaultTableModel) jTable1.getModel();
        SjzykBean bean = null;
        for (int i = 0; i < rows; i++) {
            bean = (SjzykBean) tableModel.getValueAt(i, 8);
            if (dataType.equals(bean.getDataType())) {
                list.add(bean);
            }
        }
        return list;
    }

