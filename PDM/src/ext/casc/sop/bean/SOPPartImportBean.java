package ext.casc.sop.bean;

public class SOPPartImportBean {

    /**编号*/
    private String number;
    /**名称*/
    private String name;
    /**密级*/
    private String secret;
    /**期限*/
    private String trem;
    /**专业类别*/
    private String specializedType;
    /**专业代号*/
    private String professionalCode;
    /**工序名称*/
    private String produreName;
    /**工序简号*/
    private String stationNo;
    /**部门*/
    private String department;
    /**行号*/
    private String index;

    public String getNumber() {
        return number;
    }

    public void setNumber(String number) {
        this.number = number;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSecret() {
        return secret;
    }

    public void setSecret(String secret) {
        this.secret = secret;
    }

    public String getTrem() {
        return trem;
    }

    public void setTrem(String trem) {
        this.trem = trem;
    }

    public String getSpecializedType() {
        return specializedType;
    }

    public void setSpecializedType(String specializedType) {
        this.specializedType = specializedType;
    }

    public String getProfessionalCode() {
        return professionalCode;
    }

    public void setProfessionalCode(String professionalCode) {
        this.professionalCode = professionalCode;
    }

    public String getProdureName() {
        return produreName;
    }

    public void setProdureName(String produreName) {
        this.produreName = produreName;
    }

    public String getStationNo() {
        return stationNo;
    }

    public void setStationNo(String stationNo) {
        this.stationNo = stationNo;
    }

    public String getDepartment() {
        return department;
    }

    public void setDepartment(String department) {
        this.department = department;
    }

    public String getIndex() {
        return index;
    }

    public void setIndex(String index) {
        this.index = index;
    }
}
